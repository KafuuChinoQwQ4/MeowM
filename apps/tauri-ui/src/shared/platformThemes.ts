function normalizeName(name: string): string {
  return name
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[’‘]/g, "'")
    .replace(/[\s_-]+/g, ' ')
    .trim();
}
const brandMatchers = platformThemes
  .flatMap((theme) =>
    theme.aliases.map((alias) => {
      const name = normalizeName(alias);
      const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      // Latin aliases need word boundaries: Gate must not color a platform named gateway.
      const prefix = /^[a-z0-9]/.test(name) ? '(?<![a-z0-9])' : '';
      const suffix = /[a-z0-9]$/.test(name) ? '(?![a-z0-9])' : '';
      return { theme, length: name.length, pattern: new RegExp(prefix + escaped + suffix) };
    }),
  )
  .sort((a, b) => b.length - a.length);

export function searchPlatformThemes(query: string) {
  const normalized = normalizeName(query);
  const suggestions = [
    ...platformThemes.map((theme) => ({ ...theme, category: theme.group })),
    { ...CASH_PLATFORM_THEME, category: 'cash', aliases: ['现金', '現金', 'Cash'] },
  ];
  return suggestions
    .map((theme) => {
      const names = [theme.name, ...theme.aliases].map(normalizeName);
      const rank =
        !normalized || names.includes(normalized)
          ? 0
          : names.some((name) => name.startsWith(normalized))
            ? 1
            : 2;
      return { theme, names, rank };
    })
    .filter(({ names }) => !normalized || names.some((name) => name.includes(normalized)))
    .sort((a, b) => a.rank - b.rank)
    .map(({ theme }) => theme);
}

export function resolvePlatformTheme(name: string, category = ''): PlatformTheme {
  const normalized = normalizeName(name);
  const match = brandMatchers.find(({ pattern }) => pattern.test(normalized));
  if (match) return match.theme;
  if (
    category === 'cash' ||
    /现金|現金/.test(normalized) ||
    /^(cash|cash wallet)$/.test(normalized)
  )
    return CASH_PLATFORM_THEME;
  return DEFAULT_PLATFORM_THEME;
}

export function platformThemeStyle(theme: PlatformTheme) {
  return { background: theme.background, color: theme.foreground, borderColor: theme.border };
}
